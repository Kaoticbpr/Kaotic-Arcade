#!/usr/bin/env python3
"""Build the table: starter table + layout + script + art -> dist/<TABLE_FILE>.vpx

Needs vpxtool on the PATH (https://github.com/francisdb/vpxtool, or `cargo install vpxtool --locked`).

    python3 tools/build.py            # build dist/YoRetro.vpx
    python3 tools/build.py --no-pack  # only write build/expanded (handy for diffing)
"""
import argparse
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TABLE = HERE.parent
sys.path.insert(0, str(HERE))
import layout  # noqa: E402

TABLE_FILE = "YoRetro"
TABLE_NAME = "Yo! Retro (Original 2026)"
AUTHOR = "KaoticBPR"
VERSION = "0.2.0"

# Callout events the script plays (see VOICE_SCRIPT.md); takes are sounds/voice/vo_<event>_<n>.
VOICE_EVENTS = {
    "start", "player_added", "next_ball", "shoot_again", "skill_shot", "ball_saved", "drain", "bonus_x",
    "ramp", "orbit", "extra_ball_lit", "extra_ball", "lock_lit", "lock", "multiball", "jackpot",
    "half_a_dozen", "segment_1", "segment_2", "segment_3", "segment_4", "segment_5", "segment_done",
    "segment_over", "more_time", "finale_lit", "finale", "finale_end", "tilt_warning", "tilt",
    "game_over", "high_score", "attract",
}

# Legends Unchained runs VPX standalone 10.8.0, which refuses newer files. base/ is a 10.9 table, so the build
# saves it as 10.8: these are the only parts and fields this table uses that 10.8 doesn't know (checked
# against the 10.8.0 exampleTable.vpx and strippedTable.vpx from the vpinball repo).
VPX_FILE_VERSION = "1080"
VPX_109_ITEM_TYPES = {"PartGroup"}
VPX_109_ITEM_FIELDS = {"part_group_name"}
VPX_109_GAMEDATA_FIELDS = {"exposure"}
VPX_109_RENDERPROBE_FIELDS = {"disable_light_reflection"}

# Art the build picks up when present (see art/README.md). Missing files are fine.
ART = {
    "playfield": TABLE / "art" / "playfield.png",
}


def run(*cmd):
    print("+", " ".join(str(c) for c in cmd))
    subprocess.run([str(c) for c in cmd], check=True)


def audio_script(sound_names):
    """VBScript telling 35_audio.vbs which voice takes and music the build included."""
    takes = {}
    for name in sound_names:
        m = re.fullmatch(r"vo_(\w+?)_(\d+)", name)
        if m:
            takes.setdefault(m.group(1), set()).add(int(m.group(2)))
    lines = ["' ---- generated by tools/build.py from the files in sounds/ ----",
             f"Const HasThemeMusic = {'True' if 'music_theme' in sound_names else 'False'}",
             "Function VoiceVariants(evt)", "\tSelect Case evt"]
    for event in sorted(takes):
        if event not in VOICE_EVENTS:
            print(f"voice: warning, vo_{event}_* is not an event the script plays")
        count = 0
        while count + 1 in takes[event]:
            count += 1
        if count != len(takes[event]):
            print(f"voice: warning, vo_{event}_* takes must be numbered 1, 2, 3 ... without gaps")
        lines.append(f'\t\tCase "{event}" : VoiceVariants = {count}')
    lines += ["\t\tCase Else : VoiceVariants = 0", "\tEnd Select", "End Function"]
    print(f"voice: {sum(len(t) for t in takes.values())} takes for {len(takes)} of {len(VOICE_EVENTS)} events;"
          f" theme music {'in' if 'music_theme' in sound_names else 'not added yet'}")
    return "\n".join(lines) + "\n"


def write_script(expanded, sound_names):
    parts = [p.read_text() for p in sorted((TABLE / "script").glob("*.vbs"))] + [audio_script(sound_names)]
    text = "\r\n".join(p.replace("\r\n", "\n").replace("\n", "\r\n") for p in parts)
    text = text.replace("@@VERSION@@", VERSION)
    (expanded / "script.vbs").write_text(text, newline="")


def write_info(expanded):
    info_path = expanded / "info.json"
    info = json.loads(info_path.read_text())
    info.update(table_name=TABLE_NAME, author_name=AUTHOR, table_version=VERSION,
                table_blurb="Yo! Retro: the AtGames table review show by KaoticBPR and Half-A-Dozen, as a pinball table.",
                table_description="Built from source in the Kaotic-Arcade repo (tables/yo-retro).")
    info_path.write_text(json.dumps(info, indent=2))


def add_art(expanded):
    gamedata_path = expanded / "gamedata.json"
    gamedata = json.loads(gamedata_path.read_text())
    images_path = expanded / "images.json"
    images = json.loads(images_path.read_text())
    playfield = ART["playfield"]
    if playfield.exists():
        (expanded / "images").mkdir(exist_ok=True)
        shutil.copy(playfield, expanded / "images" / "playfield.png")
        images.append({"name": "playfield", "path": "playfield.png", "alpha_test_value": -1.0,
                       "is_opaque": True})
        gamedata["image"] = "playfield"
        print("art: playfield.png added")
    else:
        print("art: no art/playfield.png yet, using the plain playfield")
    images_path.write_text(json.dumps(images, indent=2))
    gamedata_path.write_text(json.dumps(gamedata, indent=2))


def save_as_vpx_108(expanded):
    items = expanded / "gameitems"
    index_path = expanded / "gameitems.json"
    index = json.loads(index_path.read_text())
    dropped = [e for e in index if e["file_name"].split(".")[0] in VPX_109_ITEM_TYPES]
    for entry in dropped:
        (items / entry["file_name"]).unlink()
    index_path.write_text(json.dumps([e for e in index if e not in dropped], indent=2))
    for path in items.glob("*.json"):
        item = json.loads(path.read_text())
        for fields in item.values():
            for field in VPX_109_ITEM_FIELDS:
                fields.pop(field, None)
        path.write_text(json.dumps(item, indent=2))
    for name, fields in (("gamedata.json", VPX_109_GAMEDATA_FIELDS), ("renderprobes.json", VPX_109_RENDERPROBE_FIELDS)):
        path = expanded / name
        data = json.loads(path.read_text())
        for entry in data if isinstance(data, list) else [data]:
            for field in fields:
                entry.pop(field, None)
        path.write_text(json.dumps(data, indent=2))
    (expanded / "version.txt").write_text(VPX_FILE_VERSION)
    print(f"vpx: saved as file version {VPX_FILE_VERSION} (VPX 10.8), dropped {len(dropped)} part groups")


def add_sounds(expanded):
    """Every sounds/**/<name>.wav|ogg|mp3 becomes a table sound the script can play by <name>."""
    files = [f for f in sorted((TABLE / "sounds").rglob("*")) if f.suffix.lower() in (".wav", ".ogg", ".mp3")]
    stems = [f.stem for f in files]
    dupes = sorted({n for n in stems if stems.count(n) > 1})
    if dupes:
        sys.exit(f"sounds: these names are used by more than one file: {', '.join(dupes)}")
    sounds_path = expanded / "sounds.json"
    sounds = json.loads(sounds_path.read_text())
    if files:
        (expanded / "sounds").mkdir(exist_ok=True)
    for f in files:
        shutil.copy(f, expanded / "sounds" / f.name)
        # Music is stereo and plays from the backglass; the playfield output is for positional (mono) effects.
        target = "backglass" if f.parent.name == "music" else "table"
        sounds.append({"name": f.stem, "path": f.name, "internal_name": f.stem, "fade": 0, "volume": 0,
                       "balance": 0, "output_target": target})
    sounds_path.write_text(json.dumps(sounds, indent=2))
    print(f"sounds: {len(files)} added")
    return stems


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-pack", action="store_true", help="stop after writing build/expanded")
    args = ap.parse_args()

    build = TABLE / "build"
    expanded = build / "expanded"
    if build.exists():
        shutil.rmtree(build)
    shutil.copytree(TABLE / "base", expanded)

    names = layout.apply(expanded)
    print(f"layout: {len(names)} parts added")
    save_as_vpx_108(expanded)
    sound_names = add_sounds(expanded)
    write_script(expanded, sound_names)
    write_info(expanded)
    add_art(expanded)
    if args.no_pack:
        return

    vpxtool = shutil.which("vpxtool")
    if not vpxtool:
        sys.exit("vpxtool not found on PATH: install it from https://github.com/francisdb/vpxtool")
    dist = TABLE / "dist"
    dist.mkdir(exist_ok=True)
    out = dist / f"{TABLE_FILE}.vpx"
    run(vpxtool, "assemble", "-f", expanded, out)
    run(vpxtool, "verify", out)
    # Legends Unchained reads <table>.ini from beside the .vpx, so dist/ is what goes on the USB drive.
    shutil.copy(TABLE / "legends" / "table.ini", dist / f"{TABLE_FILE}.ini")
    print(f"built {out} and {TABLE_FILE}.ini")
    # The Table Manager takes these as the launcher wheel image and the loading backglass.
    for name in ("launcher.png", "backglass.png"):
        if (TABLE / "art" / name).exists():
            shutil.copy(TABLE / "art" / name, dist / name)
            print(f"art: {name} copied to dist/")


if __name__ == "__main__":
    main()
